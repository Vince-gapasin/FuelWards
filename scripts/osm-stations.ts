// Pure helpers for turning OpenStreetMap fuel stations into FuelWards station rows.
// Used by scripts/import-osm-stations.ts and covered by scripts/__tests__/osm-stations.test.ts.

export type OsmElement = {
  type: 'node' | 'way' | 'relation';
  id: number;
  lat?: number;
  lon?: number;
  center?: { lat: number; lon: number };
  tags?: Record<string, string>;
};

export type StationRow = {
  osmId: number;
  brandSlug: string | null;
  name: string;
  address: string | null;
  city: string | null;
  lat: number;
  lng: number;
};

// The generated migration upserts these into public.brands. Patterns match brand, name and
// operator tags. Colours are only used for map pins and are not official brand colours.
export const BRANDS: { slug: string; label: string; color: string; pattern: RegExp }[] = [
  { slug: 'petron', label: 'Petron', color: '#011D39', pattern: /\bpetron\b/i },
  { slug: 'shell', label: 'Shell', color: '#DD1D21', pattern: /\bshell\b/i },
  { slug: 'caltex', label: 'Caltex', color: '#0A5DA6', pattern: /\bcaltex\b|\bchevron\b/i },
  { slug: 'seaoil', label: 'Seaoil', color: '#00BF63', pattern: /\bsea\s?oil\b/i },
  { slug: 'unioil', label: 'Unioil', color: '#46D755', pattern: /\bunioil\b/i },
  { slug: 'cleanfuel', label: 'Cleanfuel', color: '#034B93', pattern: /\bclean\s?fuel\b/i },
  { slug: 'phoenix', label: 'Phoenix', color: '#F28C00', pattern: /\bphoenix\b/i },
  { slug: 'jetti', label: 'Jetti', color: '#E30613', pattern: /\bjetti\b/i },
  { slug: 'flyingv', label: 'Flying V', color: '#1B3F94', pattern: /\bflying\s?v\b/i },
  { slug: 'ptt', label: 'PTT', color: '#1C4E9D', pattern: /\bptt\b/i },
  { slug: 'total', label: 'TotalEnergies', color: '#C8102E', pattern: /\btotal(\s?energies)?\b/i },
  { slug: 'unofuel', label: 'Uno Fuel', color: '#F7941D', pattern: /\buno(\s?fuel)?\b/i },
  { slug: 'metrooil', label: 'Metro Oil', color: '#1E3A8A', pattern: /\bmetro\s?oil\b|^metro$/i },
  { slug: 'globaloil', label: 'Global Oil', color: '#0F766E', pattern: /\bglobal\s?oil\b/i },
  {
    slug: 'petrogazz',
    label: 'Petro Gazz',
    color: '#0057B8',
    pattern: /\bpetro\s?gazz\b|^gazz\b/i,
  },
  { slug: 'rephil', label: 'RePhil', color: '#D97706', pattern: /\brephil\b/i },
];

/** Which FuelWards brand an OSM station belongs to, or null for independents. */
export function detectBrand(tags: Record<string, string> = {}): string | null {
  for (const key of ['brand', 'name', 'operator', 'name:en']) {
    const value = tags[key];
    if (!value) continue;
    const match = BRANDS.find((b) => b.pattern.test(value));
    if (match) return match.slug;
  }
  return null;
}

/**
 * OSM ids are only unique per element type, so the type is folded into one number:
 * node → id·10+1, way → id·10+2, relation → id·10+3.
 */
export function encodeOsmId(type: OsmElement['type'], id: number): number {
  return id * 10 + { node: 1, way: 2, relation: 3 }[type];
}

export function toStation(el: OsmElement): StationRow | null {
  const lat = el.lat ?? el.center?.lat;
  const lng = el.lon ?? el.center?.lon;
  if (lat == null || lng == null) return null;

  const tags = el.tags ?? {};
  // Abandoned or disused stations still carry amenity=fuel in some edits.
  if (tags.disused === 'yes' || tags.abandoned === 'yes' || tags['disused:amenity']) return null;

  const brandSlug = detectBrand(tags);
  const brandLabel = BRANDS.find((b) => b.slug === brandSlug)?.label;
  const name = (tags.name ?? tags.brand ?? brandLabel ?? 'Fuel station').trim();
  const street = [tags['addr:housenumber'], tags['addr:street']].filter(Boolean).join(' ').trim();
  const city = tags['addr:city']?.trim() || null;

  return {
    osmId: encodeOsmId(el.type, el.id),
    brandSlug,
    name,
    address: street || null,
    city,
    lat: Math.round(lat * 1e7) / 1e7,
    lng: Math.round(lng * 1e7) / 1e7,
  };
}

const sqlText = (v: string | null) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);

/** An idempotent SQL migration: upserts every station by osm_id. */
export function toSql(stations: StationRow[], source: string): string {
  const rows = stations.map(
    (s) =>
      `  (${sqlText(s.brandSlug)}, ${sqlText(s.name)}, ${sqlText(s.address)}, ${sqlText(s.city)}, ${s.lat}, ${s.lng}, ${s.osmId})`,
  );
  return `-- Generated by scripts/import-osm-stations.ts from ${source}.
-- Station data © OpenStreetMap contributors, available under the Open Database License (ODbL).
-- Re-running the importer produces a new migration that updates existing rows by osm_id.

delete from public.stations where osm_id is null and name like '%(demo)';

insert into public.brands (slug, name, color) values
${BRANDS.map((b) => `  (${sqlText(b.slug)}, ${sqlText(b.label)}, ${sqlText(b.color)})`).join(',\n')}
on conflict (slug) do update set name = excluded.name, color = excluded.color;

insert into public.stations (brand_id, name, address, city, location, osm_id)
select b.id, v.name, v.address, v.city,
       extensions.st_setsrid(extensions.st_makepoint(v.lng, v.lat), 4326)::extensions.geography,
       v.osm_id
from (values
${rows.join(',\n')}
) as v (brand, name, address, city, lat, lng, osm_id)
left join public.brands b on b.slug = v.brand
on conflict (osm_id) do update set
  brand_id = excluded.brand_id,
  name = excluded.name,
  address = excluded.address,
  city = excluded.city,
  location = excluded.location;
`;
}
